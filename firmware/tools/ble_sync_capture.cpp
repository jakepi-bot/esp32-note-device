// Dumps the exact packet stream one note produces over Bluetooth, as hex, so
// the phone's half (web/ble-note-relay) can be checked against the firmware's
// own bytes instead of a hand-written copy of them.
//
// This is a dev tool, not a test: `web/ble-note-relay/selftest.mjs` reads the
// fixture it prints (test/transfer-fixture.txt) and rebuilds the same WAV from
// it. Regenerate after changing notes_ble.cpp:
//
//   cmake --build <build dir> --target hg_ble_capture
//   ./hg_ble_capture > web/ble-note-relay/test/transfer-fixture.txt
//
// Everything here is deterministic: with no argument the note's bytes are a
// formula, not random. Pass a file and it becomes the note instead, which is how
// a real recording is put through the same framing for an end-to-end check
// against the notes endpoint:
//
//   ./hg_ble_capture tests/fixtures/voice-notes/sample.wav > /tmp/fixture.txt
//
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

#include "hg/crypto.hpp"
#include "notes/notes_ble.hpp"

namespace {

using hgp::notes::BleNote;
using hgp::notes::BleSource;
using hgp::notes::BleSync;

class MemoryCard final : public BleSource {
 public:
  std::string id = "epaper-20261120T081504-0001";
  std::vector<uint8_t> audio;
  uint32_t duration_s = 7;

  bool ready() const override { return true; }
  std::vector<BleNote> pending() override { return {{id, size(), duration_s, digest(), recorded_at()}}; }
  bool open(std::string_view want, BleNote& out) override {
    if (want != id) return false;
    at_ = 0;
    out = {id, size(), duration_s, digest(), recorded_at()};
    return true;
  }
  size_t read(uint8_t* out, size_t max) override {
    const size_t left = audio.size() - at_;
    const size_t n = max < left ? max : left;
    std::memcpy(out, audio.data() + at_, n);
    at_ += n;
    return n;
  }
  bool seek(uint32_t offset) override {
    if (offset > audio.size()) return false;
    at_ = offset;
    return true;
  }
  void close() override { at_ = 0; }
  bool mark_synced(std::string_view) override { return true; }

  uint32_t size() const { return static_cast<uint32_t>(audio.size()); }
  std::string digest() const {
    const auto d = hg::crypto::sha256(audio.data(), audio.size());
    return hg::crypto::hex(d.data(), d.size());
  }
  static const char* recorded_at() { return "2026-11-20T08:15:04Z"; }

 private:
  size_t at_ = 0;
};

void print_hex(const uint8_t* data, size_t len) {
  for (size_t i = 0; i < len; ++i) std::printf("%02x", data[i]);
  std::printf("\n");
}

}  // namespace

int main(int argc, char** argv) {
  MemoryCard card;
  if (argc > 1) {
    // A real note: the bytes of the file the device recorded (a WAV on the card).
    std::FILE* f = std::fopen(argv[1], "rb");
    if (!f) {
      std::fprintf(stderr, "cannot open %s\n", argv[1]);
      return 1;
    }
    uint8_t buf[4096];
    size_t n;
    while ((n = std::fread(buf, 1, sizeof(buf), f)) > 0) card.audio.insert(card.audio.end(), buf, buf + n);
    std::fclose(f);
    // A real WAV says how long it is: walk the chunk list for `fmt ` (byte rate
    // at +8) and `data` (its size), since a file may carry other chunks first.
    if (card.audio.size() > 44 && std::memcmp(card.audio.data(), "RIFF", 4) == 0) {
      const auto le32 = [&card](size_t at) {
        return static_cast<uint32_t>(card.audio[at]) | static_cast<uint32_t>(card.audio[at + 1]) << 8 |
               static_cast<uint32_t>(card.audio[at + 2]) << 16 | static_cast<uint32_t>(card.audio[at + 3]) << 24;
      };
      uint32_t byte_rate = 0, data = 0;
      for (size_t at = 12; at + 8 <= card.audio.size();) {
        const uint32_t size = le32(at + 4);
        if (std::memcmp(card.audio.data() + at, "fmt ", 4) == 0 && at + 16 <= card.audio.size()) byte_rate = le32(at + 16);
        if (std::memcmp(card.audio.data() + at, "data", 4) == 0) {
          data = size;
          break;
        }
        at += 8 + size + (size & 1);
      }
      if (byte_rate > 0 && data > 0) card.duration_s = (data + byte_rate - 1) / byte_rate;
    }
  } else {
    // 3000 bytes: a fraction of a real note, enough for 18 blocks at an iOS MTU,
    // and the same bytes every run.
    card.audio.resize(3000);
    for (size_t i = 0; i < card.audio.size(); ++i) card.audio[i] = static_cast<uint8_t>((i * 31 + 7) & 0xFF);
  }

  BleSync sync;
  sync.begin(&card);
  sync.set_mtu(185);

  std::printf("# Bluetooth note-sync fixture: generated by firmware/tools/ble_sync_capture.cpp\n");
  std::printf("# Packet tags: H=0x48 header, B=0x42 block, L=0x4c text, E=0x45 error, K=0x4b end\n");
  std::printf("AUDIO_LEN %u\n", card.size());
  std::printf("AUDIO_CRC %08x\n", hgp::notes::crc32(card.audio.data(), card.audio.size()));
  std::printf("AUDIO_SHA256 %s\n", card.digest().c_str());
  std::printf("MTU 185\n");

  uint32_t now = 0;
  unsigned packets = 0;
  unsigned blocks = 0;
  bool seen_end = false;
  const auto sink = [&packets, &blocks, &seen_end](const uint8_t* data, size_t len) {
    std::printf("PACKET ");
    print_hex(data, len);
    ++packets;
    if (len > 0 && data[0] == BleSync::kTagBlock) ++blocks;
    if (len > 0 && data[0] == BleSync::kTagEnd) seen_end = true;
    return true;
  };

  sync.command("get next", now);
  for (unsigned round = 0; round < 400 && !seen_end; ++round) {
    sync.tick(now, sink);
    now += 20;
    // This phone takes everything it is given, so it acknowledges the whole
    // window every round: exactly what a well-behaved client does.
    char ack[32];
    std::snprintf(ack, sizeof(ack), "ack %u", sync.progress().sent);
    sync.command(ack, now);
  }
  std::printf("PACKETS_BLOCKS %u\n", blocks);
  std::printf("# %u packets\n", packets);
  return 0;
}
